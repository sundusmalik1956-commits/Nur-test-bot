# دالة مساعدة لجلب النص حسب اللغة
# =====================================================

def get_text(user_id, key, *args):
    """جلب النص المترجم حسب لغة المستخدم"""
    from handlers.user_session import user_data
    session = user_data.get(user_id)
    if session and session.language in TEXTS:
        lang = session.language
    else:
        lang = "arabic"
    
    text = TEXTS[lang].get(key, TEXTS["arabic"].get(key, key))
    if args:
        return text.format(*args)
    return text
