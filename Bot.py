def handle_answer(user_id, message_text):
    """معالجة إجابة المستخدم (اختيار من متعدد)"""
    session = user_data.get(user_id)
    if not session or not session.waiting_for_answer:
        return
    
    # تحقق من الوقت
    if session.start_time and time.time() - session.start_time > session.time_limit:
        bot.send_message(user_id, get_text(user_id, "time_up"))
        show_final_results(user_id)
        return
    
    session.waiting_for_answer = False
    answer = message_text.strip()
    correct = session.current_correct_answer
    
    if answer == correct:
        session.scores[session.current_question_type] += 1
        bot.send_message(user_id, get_text(user_id, "correct_answer"))
    else:
        bot.send_message(user_id, get_text(user_id, "wrong_answer"))
    
    # الانتقال للسؤال التالي حسب القسم
    if session.current_section == 1:
        ask_next_vocab_question(user_id)
    elif session.current_section == 2:
        ask_next_reading_question(user_id)
    elif session.current_section == 3:
        ask_next_listening_question(user_id)

